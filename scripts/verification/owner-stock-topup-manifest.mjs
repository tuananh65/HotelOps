import fs from 'node:fs';
import assert from 'node:assert/strict';

const path = process.argv[2];
assert.ok(path, 'Pass the receipt manifest generated by Invoke-OwnerStockTopup.ps1');
const rows = JSON.parse(fs.readFileSync(path, 'utf8').replace(/^\uFEFF/, ''));
assert.equal(rows.length, 16);
assert.equal(new Set(rows.map(r => r.document_id)).size, 2);
assert.equal(new Set(rows.map(r => r.warehouse)).size, 2);
for (const row of rows) {
  assert.equal(row.actual_qty, 100);
  assert.equal(row.status, 'POSTED');
  assert.match(row.document_no, /^OWNER-261125-/);
  assert.match(row.note, /Owner-authorized estimate; not manufacturer expiry/);
}
console.log('PASS: 2 posted receipts, 16 lines, 100 base units each, internal-deadline provenance.');
